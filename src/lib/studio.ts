export function projectHref(p: Project) {
  return "/work/" + p.sector + "/" + encodeURIComponent(p.slug || p.id);
}
export function safeUrl(value: string | null | undefined) {
  if (!value) return "";
  try {
    const u = new URL(value);
    return ["https:", "http:"].includes(u.protocol) ? u.href : "";
  } catch {
    return "";
  }
}
export function isVideo(url: string) {
  try {
    return /\.(mp4|webm|mov|ogg)$/i.test(new URL(url).pathname);
  } catch {
    return false;
  }
}
export function pageHead(title: string, description: string, path: string, image?: string) {
  return {
    meta: [
      { title },
      { name: "description", content: description },
      { property: "og:title", content: title },
      { property: "og:description", content: description },
      { property: "og:type", content: "website" },
      { property: "og:url", content: studio.origin + path },
      ...(image ? [{ property: "og:image", content: image }] : []),
    ],
    links: [{ rel: "canonical", href: studio.origin + path }],
  };
}
